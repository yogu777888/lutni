/** Любой цвет `#rrggbb` — тем же приглушением (кольца турниров в левой панели — цвет логотипа). */
export function softTone(hex: string): string {
  const lin = (v: number) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4)
  const [r, g, b] = [1, 3, 5].map((i) => lin(parseInt(hex.slice(i, i + 2), 16) / 255))
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
  const h = Math.atan2(0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s, 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s)
  const [L, a2, b2] = [0.74, 0.12 * Math.cos(h), 0.12 * Math.sin(h)]
  const l3 = (L + 0.3963377774 * a2 + 0.2158037573 * b2) ** 3
  const m3 = (L - 0.1055613458 * a2 - 0.0638541728 * b2) ** 3
  const s3 = (L - 0.0894841775 * a2 - 1.291485548 * b2) ** 3
  const out = [
    4.0767416621 * l3 - 3.3077115913 * m3 + 0.2309699292 * s3,
    -1.2684380046 * l3 + 2.6097574011 * m3 - 0.3413193965 * s3,
    -0.0041960863 * l3 - 0.7034186147 * m3 + 1.707614701 * s3,
  ]
  const enc = (v: number) => {
    const c = Math.min(1, Math.max(0, v))
    return Math.round((c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055) * 255)
      .toString(16)
      .padStart(2, '0')
  }
  return `#${out.map(enc).join('')}`
}

