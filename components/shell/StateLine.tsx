import { pluralN } from '@/lib/format'

/** «1 матч», «3 матча», «10 матчей». */
export const matchesN = (n: number) => pluralN(n, ['матч', 'матча', 'матчей'])

/**
 * Подпись под названием в обеих боковых панелях — сколько матчей и что с ними сейчас: «10 матчей · 3 идут» (серым, без красного),
 * «6 матчей · начало в 22:00» (ещё ничего не начиналось), «· ещё 2 с 22:00» (часть уже сыграна), «· все сыграны».
 * Одна схема у турниров слева и подборок справа (владелец согласился: голые цифры справа читались как счётчик
 * непрочитанных, а статичные описания подборок повторяли названия).
 */
export function StateLine({
  total,
  live,
  next,
  started,
  pending,
  soon = false,
}: {
  total: number
  live: number
  next: string | null
  started: boolean
  pending: number
  /** «Скоро начнутся»: только «ближайший в 20:00» — число матчей там ничего не говорит, а «8 матчей · начало в 20:00»
   * повторяло строку «Главных матчей» над ней (владелец согласился) */
  soon?: boolean
}) {
  if (soon && next && !live) return <>ближайший в {next}</>
  // идут все — без повтора числа: «4 матча, все идут» вместо «4 матча · 4 идут»
  if (live && live === total) return <>{total === 1 ? '1 матч, идёт' : `${matchesN(total)}, все идут`}</>
  // словами, без сокращений (владелец: «"4 в игре" непонятно — может "4 идут"? и "с 20:00" — может "начало 20:00"?»)
  // часть уже сыграна — сколько впереди и с какого времени: «ещё 2 с 21:00» («дальше в 21:00» владельцу было непонятно,
  // «следующий в 21:00» не влезает в панель 248px)
  const rest = pending > 1 ? `ещё ${pending} с ${next}` : `ещё 1 в ${next}`
  const state = live ? null : next ? (started ? rest : `начало в ${next}`) : started ? 'все сыграны' : ''
  return (
    <>
      {matchesN(total)}
      {/* разделитель всегда «·», вся подпись серая, без красного: красные слова пестрили, красная точка в строке давала
          то «·», то «●», а точки на флагах владелец убрал («бесят красные точки в лигах»); «идёт» — в центре */}
      {live || state ? ' · ' : ''}
      {live ? `${live} ${live % 10 === 1 && live % 100 !== 11 ? 'идёт' : 'идут'}` : state}
    </>
  )
}

