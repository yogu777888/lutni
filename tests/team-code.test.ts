describe('teamCode', () => {
  it('коды из списков', () => {
    expect(teamCode('Реал Мадрид')).toBe('РМА')
    expect(teamCode('Россия')).toBe('РОС')
  })

  it('сборные с припиской — код страны, клубы с припиской — код клуба', () => {
    expect(teamCode('Россия U21')).toBe('РОС')
    expect(teamCode('Норвегия (жен.)')).toBe('НОР')
    expect(teamCode('Мексика U17 (жен.)')).toBe('МЕК')
    expect(teamCode('Арсенал U21')).toBe('АРС')
  })

  it('нет в списках — первые три буквы', () => {
    expect(teamCode('Rokycany')).toBe('ROK')
    expect(teamCode('Petřín Plzeň')).toBe('PET')
  })

  it('у сборных коды не повторяются', () => {
    const all = [...NATION_CODES.values()]
    expect(all.filter((c, i) => all.indexOf(c) !== i)).toEqual([])
  })

  it('в одной лиге коды не повторяются', () => {
    for (const league of LEAGUES) {
      const all = league.map(teamCode)
      expect(all.every((c) => /^[А-ЯЁ]{3}$/.test(c))).toBe(true)
      expect(all.filter((c, i) => all.indexOf(c) !== i)).toEqual([])
    }
  })
})
