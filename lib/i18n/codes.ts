/** Приписка сборной или второго состава после названия: «U21», «(жен.)», «U17 (жен.)», «B». */
const SUFFIX = /\s+(?:U\d{2}(?:\s+\(жен\.\))?|\(жен\.\)|B)$/

/** Код команды по русскому названию; нет в списках — первые три буквы («Rokycany» — ROK). */
export function teamCode(name: string): string {
  const full = name.trim().toLowerCase()
  const base = full.replace(SUFFIX, '')
  const known = CLUB_CODES.get(full) ?? CLUB_CODES.get(base) ?? NATION_CODES.get(base)
  if (known) return known
  return (base.match(/\p{L}/gu) ?? []).slice(0, 3).join('').toUpperCase()
}
