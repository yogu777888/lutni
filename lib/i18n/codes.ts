/**
 * Трёхбуквенные коды команд, как на табло в трансляциях: «Арсенал» — АРС, «Реал Мадрид» — РМА, Россия — РОС.
 * Нужны в плашке над табло на компьютере, когда полные названия в середине не помещаются (владелец сгенерировал списки
 * в ChatGPT по нашему словарю `TEAMS` и стран `COUNTRIES` в `ru.ts`). Ключ — русское название, как его выдаёт `ruTeam`.
 * Повторы в разных лигах допустимы (Милан и Миллуолл — МИЛ); в одной лиге и у сборных — нет (тест `tests/team-code.test.ts`).
 * Новая команда в `TEAMS` — допишите ей код здесь, иначе возьмутся первые три буквы.
 */

function codes(src: string): Map<string, string> {
  const map = new Map<string, string>()
  for (const line of src.split('\n')) {
    const i = line.lastIndexOf('=')
    if (i > 0) map.set(line.slice(0, i).trim().toLowerCase(), line.slice(i + 1).trim())
  }
  return map
}

